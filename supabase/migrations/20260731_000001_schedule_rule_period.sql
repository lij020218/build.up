-- ─────────────────────────────────────────────────────────────────
--  근무 규칙 적용 기간 (2026-07-31 사장님 요청)
--
--   "지금은 근무표를 배정하면 모든 연도와 월에 미리 체크가 되어 있는데
--    한 달 단위나 1년 단위 이렇게 선택하게 할까?"
--
--  종전 staff_schedule_rules 는 요일·시간만 있어 기간 개념이 없었다 —
--  여름 두 달만 일하는 알바도 내년 캘린더에 근무자로 무한히 칠해지는
--  "확정처럼 보이는 미확정" 문제.
--
--  결정(사장님): 강제 선택이 아니라 **기간 옵션 + 프리셋**.
--   · effective_until NULL = 계속 (기본, 기존 데이터 전부 여기 해당 → 동작 불변)
--   · 프리셋: 계속 / 이번 달까지 / 1년간 / 직접 날짜 — 화면에서 이 컬럼 하나로 표현
--   · 시작일(effective_from)은 아직 없음 — "다음 달부터" 수요가 실제로 오면 별도 추가
--     (컬럼을 미리 깔면 안 쓰는 반쪽 기능이 됨)
--
--  해석은 shared SSOT(resolveShiftForDate)가 한 곳에서 — 기간 밖 날짜는 근무 아님.
-- ─────────────────────────────────────────────────────────────────

ALTER TABLE public.staff_schedule_rules
  ADD COLUMN IF NOT EXISTS effective_until date;

COMMENT ON COLUMN public.staff_schedule_rules.effective_until IS
  '이 날짜까지(포함) 규칙 적용. NULL = 계속. 기간 밖 날짜는 근무로 해석하지 않는다.';
